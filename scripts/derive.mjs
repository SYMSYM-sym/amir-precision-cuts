function parseArgs(argv) {
  const only = [];
  let force = false; let append = false; let dryRun = false; let count = null; let config = null;
  for (const a of argv) {
    if (a.startsWith('--only=')) only.push(...a.slice(7).split(',').map((s) => s.trim()).filter(Boolean));
    else if (a === '--force') force = true;
    else if (a === '--append') append = true;
    else if (a === '--dry-run') dryRun = true;
    else if (a.startsWith('--count=')) count = Number(a.slice(8));
    else if (a.startsWith('--config=')) config = a.slice(9);
  }
  const bad = only.filter((s) => !ALL_STEPS.includes(s));
  if (bad.length) throw new Error(`Unknown --only step(s): ${bad.join(', ')}. Known: ${ALL_STEPS.join(', ')}`);
  return { steps: only.length ? only : ALL_STEPS, force, append, dryRun, count, config };
}

export async function derive(argv = process.argv.slice(2)) {
  const { steps, force, append, dryRun, count, config } = parseArgs(argv);
  const c = config ? loadConfig(config.startsWith('/') ? config : join(ROOT, config)) : cfg;

  const willCallApi = steps.filter((s) => JUDGMENT.has(s));
  console.log(`derive: ${c.business.name} — steps: ${steps.join(', ')}`);
  if (dryRun) {
    console.log(`DRY RUN — no files written, no API calls made.`);
    console.log(`Model provider: ${provider() || 'NONE — judgment artifacts will fail'}`);
    console.log(`Estimated model calls: ${willCallApi.length} (cap ${MAX_DERIVE_API_CALLS})`);
    for (const s of steps) {
      const j = JUDGMENT.has(s);
      console.log(`  ${j ? 'API ' : 'PURE'}  ${s}${j ? ' (judgment — model call + human review)' : ''}`);
    }
    return { dryRun: true, steps };
  }

  const slice = { business: c.business, location: c.location, brand: c.brand, content: c.content, services: c.services };

  for (const step of steps) {
    switch (step) {
      case 'forbidden':
        writeGuarded(contentPath('brand', 'forbidden.yaml'), buildForbidden(c), { step, force, cfgSlice: slice });
        break;

      case 'links':
        writeGuarded(contentPath('brand', 'internal-links.yaml'), buildInternalLinks(c), { step, force, cfgSlice: slice });
        break;

      case 'authors':
        writeGuarded(authorPath(c.business.author_id), yaml.dump(buildAuthor(c), YAML_OPTS), { step, force, cfgSlice: slice });
        break;

      case 'voice': {
        const path = contentPath('brand', 'voice.md');
        if (!force && existsSync(path) && !isPristine(path)) {
          console.log(`SKIP  ${rel(path)} (hand-edited; --force to overwrite)`);
          break;
        }
        const md = stripFence(await callModel(
          'You write brand-voice guides for small service businesses. You are concrete and opinionated, never generic.',
          voicePrompt(c), 'voice.md',
        ));
        writeGuarded(path, md, { kind: 'md', step, force: true, cfgSlice: slice });
        break;
      }

      case 'queue': {
        await deriveQueue(c, { force, append, count, slice });
        break;
      }

      case 'site':
        await renderSite(c);
        console.log('WRITE site/index.html\nWRITE site/assets/styles.css\nWRITE site/robots.txt');
        break;

      case 'assets':
        runAssets(c, dryRun);
        break;

      case 'workflows':
        for (const f of buildWorkflows(c)) console.log(`WRITE ${f}`);
        break;

      case 'dashboard': {
        const p = join(ROOT, 'dashboard', 'lib', 'generated-constants.ts');
        if (existsSync(join(ROOT, 'dashboard'))) {
          mkdirSync(dirname(p), { recursive: true });
          writeFileSync(p, buildDashboardConstants(c), 'utf8');
          console.log(`WRITE ${rel(p)}`);
        } else {
          console.log('SKIP  dashboard/ (not present)');
        }
        break;
      }
      default:
        break;
    }
  }

  console.log(`\nderive complete. API calls used: ${apiCalls}/${MAX_DERIVE_API_CALLS}`);
  return { steps, apiCalls };
}

async function deriveQueue(c, { force, append, count, slice }) {
  const path = contentPath('topics', 'queue.yaml');
  const exists = existsSync(path);
  const published = exists ? (loadPublished().entries || []) : [];
  const quarantined = exists ? (loadNeedsReview().entries || []) : [];
  const hasHistory = published.length > 0 || quarantined.length > 0;

  if (force && hasHistory && !append) {
    throw new Error(
      'REFUSING --force on queue.yaml: this repo has publish history ' +
        `(${published.length} published, ${quarantined.length} quarantined).\n` +
        'Regenerating from scratch would re-add already-published and quarantined slugs and\n' +
        'break the ledger invariant (every topic in exactly ONE of queue/published/needs-review).\n' +
        'That is bug A8 reborn. Use `--only=queue --append --count=N` to add runway instead.\n' +
        '--force on the queue is a NEW-BUSINESS operation only.',
    );
  }

  // The queue is a LEDGER, not a rendered artifact: `publish-article.mjs`
  // removes a slug from it on success, so an overwrite is not idempotent — it
  // silently resurrects work already done. Every other JUDGMENT artifact is
  // protected by the derive-hash banner; the queue cannot carry one (its own
  // consumers rewrite it), so the protection has to be an explicit gate.
  if (exists && !force && !append) {
    throw new Error(
      `REFUSING to overwrite an existing queue.yaml (${existingCount(path)} topics).\n`
        + 'The queue is a ledger that publish-article.mjs mutates, so a plain rewrite is\n'
        + 'destructive rather than idempotent.\n'
        + '  --only=queue --append --count=N   add runway to the end (the normal operation)\n'
        + '  --only=queue --force              reseed from scratch (new business only)',
    );
  }

  const existingQueue = exists ? loadQueue() : [];
  const existingTitles = [
    ...existingQueue.map((t) => t.title),
    ...published.map((e) => e.title),
    ...quarantined.map((e) => e.title),
  ].filter(Boolean);

  const want = count || (append ? 10 : c.content.topics_to_seed);
  const raw = stripFence(await callModel(
    'You are an SEO editorial planner for small local service businesses. You produce topics with genuinely distinct angles, never interchangeable ones.',
    queuePrompt(c, want, existingTitles), 'queue.yaml',
  ));

  let topics;
  try {
    topics = yaml.load(raw);
  } catch (e) {
    throw new Error(`Model returned unparseable YAML for the queue: ${e.message}`);
  }

  const errors = validateTopics(topics, c);
  if (errors.length) {
    throw new Error(`Generated queue failed validation:\n${errors.map((e) => `  • ${e}`).join('\n')}`);
  }

  const { kept, dropped } = await dedupeTopics(topics, existingQueue, c);
  if (dropped.length) {
    console.log(`      deduped out ${dropped.length} topic(s) at >${c.content.queue_dedupe_max_similarity}:`);
    for (const d of dropped) console.log(`        - ${d.slug} (near ${d.near})`);
  }

  // content/topics/ does not exist in a fresh clone — the template ships
  // content/{articles,authors,brand} because those have committed files, and a
  // queue is by definition generated. Without this, EVERY new business dies on
  // ENOENT after the model call has already been spent.
  mkdirSync(dirname(path), { recursive: true });

  if (append) {
    // NEVER rewrite an existing entry (§02.4).
    const final = [...existingQueue, ...kept];
    writeFileSync(path, QUEUE_HEADER + yaml.dump(final, YAML_OPTS), 'utf8');
    console.log(`WRITE ${rel(path)} (appended ${kept.length}; ${final.length} total)`);
  } else {
    writeFileSync(path, QUEUE_HEADER + yaml.dump(kept, YAML_OPTS), 'utf8');
    console.log(`WRITE ${rel(path)} (${kept.length} topics)`);
  }
  const hyper = kept.filter((t) => t.bucket === 'hyperlocal').length;
  console.log(`      hyperlocal: ${hyper}/${kept.length} (${Math.round((hyper / Math.max(kept.length, 1)) * 100)}%, cap ~30%)`);
}

const invoked = process.argv[1] && process.argv[1].endsWith('derive.mjs');
if (invoked) {
  derive().catch((e) => {
    console.error(`\n${e.message}`);
    process.exit(1);
  });
}
