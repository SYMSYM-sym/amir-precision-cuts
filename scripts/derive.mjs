/** Validate a model-produced topic list before it can reach the queue. */
export function validateTopics(topics, c) {
  const errors = [];
  if (!Array.isArray(topics)) return ['queue output is not a YAML array'];
  const seen = new Set();
  const serviceKeys = new Set(c.services.map((s) => s.key));
  const pageKeys = new Set(['about', 'faq', 'aftercare', 'visit']);
  topics.forEach((t, i) => {
    const at = `topics[${i}]`;
    for (const k of ['slug', 'title', 'target_keyword', 'intent', 'bucket', 'notes']) {
      if (!t?.[k]) errors.push(`${at}.${k} is missing`);
    }
    if (t?.slug) {
      if (!/^[a-z0-9-]+$/.test(t.slug)) errors.push(`${at}.slug "${t.slug}" is not kebab-case`);
      if (seen.has(t.slug)) errors.push(`${at}.slug "${t.slug}" is a duplicate`);
      seen.add(t.slug);
    }
    if (t?.bucket && !BUCKETS.includes(t.bucket)) {
      errors.push(`${at}.bucket "${t.bucket}" is not in content.buckets`);
    }
    // R13: a note that is not an angle is the failure mode this whole system has.
    if (t?.notes && String(t.notes).trim().length < 60) {
      errors.push(`${at}.notes is too thin (${String(t.notes).trim().length} chars) — it must state a reason to exist, not a subject`);
    }
    for (const l of t?.internal_links || []) {
      if (l.service && !serviceKeys.has(l.service)) errors.push(`${at} links unknown service "${l.service}"`);
      if (l.page && !pageKeys.has(l.page)) errors.push(`${at} links unknown page "${l.page}"`);
    }
  });
  const hyper = topics.filter((t) => t?.bucket === 'hyperlocal').length;
  if (topics.length && hyper / topics.length > 0.35) {
    errors.push(`hyperlocal is ${Math.round((hyper / topics.length) * 100)}% of the queue (cap ~30%, R13)`);
  }
  return errors;
}

/** R13 — dedupe at the SEED gate, which is stricter than the publish gate. */
async function dedupeTopics(topics, existing, c) {
  const kept = [];
  const dropped = [];
  for (const t of topics) {
    const dup = await findNearDuplicateTopic(t, {
      threshold: c.content.queue_dedupe_max_similarity,
      queueTopics: [...existing, ...kept],
      excludeSlug: t.slug,
    });
    if (dup) dropped.push({ slug: t.slug, near: dup });
    else kept.push(t);
  }
  return { kept, dropped };
}

