#!/usr/bin/env node
/**
 * derive.mjs — the factory.
 *
 * `npm run derive` regenerates all SEVEN artifacts from business.config.yaml:
 *
 *   1. content/brand/voice.md              JUDGMENT   (one model call, then a human read)
 *   2. content/brand/forbidden.yaml        deterministic
 *   3. content/brand/internal-links.yaml   deterministic
 *   4. content/authors/<author_id>.yaml    deterministic   (§02.2b — the .yaml the grep misses)
 *   5. content/topics/queue.yaml           JUDGMENT   (one model call, deduped, human-reviewed)
 *   6. site/index.html + styles.css + robots.txt   deterministic  (§02.6 — THE SITE ITSELF)
 *   7. brand assets (favicon/icon/apple-touch/og.jpg)  deterministic
 *
 * There is no derive script in the reference build — this is new construction,
 * and 14 §B calls it "the one that decides whether you built a factory or a mold."
 *
 * FLAGS
 *   --only=voice|forbidden|links|authors|queue|site|assets|dashboard   (repeatable, comma-separated)
 *   --force      overwrite a hand-edited JUDGMENT artifact
 *   --append     queue only: generate N NEW topics and append (never rewrite)
 *   --count=N    with --append, how many new topics
 *   --dry-run    print what would regenerate + the estimated API call count, spend nothing
 *   --config=P   derive from a different config (used by the swap test)
 *
 * THE --force TRAP (§02, and it is subtle)
 * `queue.yaml` is ENGINE-MUTATED: dequeueTopic() rewrites it on every publish and
 * quarantineTopic() on every permanent failure. So on any live repo its hash stops
 * matching almost immediately, derive SKIPs it forever, and the only escape looks
 * like --force — which regenerates ~50 topics from scratch, re-adding already
 * published and quarantined slugs and breaking the ledger invariant. That is bug
 * A8 reborn. Reseeding is --append. --force on the queue is refused outright on a
 * repo with publish history.
 */
