const HASH_RE = /derive-hash:\s*([a-f0-9]{16})/;

function contentHash(body) {
  return createHash('sha256').update(body.trim()).digest('hex').slice(0, 16);
}

function bannerFor(kind, cfgHash, bodyHash) {
  const c = kind === 'yaml' ? '#' : kind === 'css' ? ' *' : '#';
  return [
    `${c} ${BANNER}`,
    `${c} config-hash: ${cfgHash}`,
    `${c} derive-hash: ${bodyHash}`,
  ].join('\n');
}

/**
 * True when the file on disk was last written by derive and has not been touched
 * since. Refining a judgment artifact by hand is expected and good — the guard
 * exists to protect that work, not to forbid it.
 */
function isPristine(path) {
  if (!existsSync(path)) return true;
  const raw = readFileSync(path, 'utf8');
  const m = raw.match(HASH_RE);
  if (!m) return false;
  const body = raw.split('\n').filter((l) => !/^[#\s*]*(?:GENERATED by|config-hash:|derive-hash:)/.test(l)).join('\n');
  return contentHash(body) === m[1];
}

function writeGuarded(path, body, { kind = 'yaml', step, force, cfgSlice }) {
  const judgment = JUDGMENT.has(step);
  if (judgment && !force && !isPristine(path)) {
    console.log(`SKIP  ${rel(path)} (hand-edited; --force to overwrite)`);
    return false;
  }
  const head = bannerFor(kind, configHash(cfgSlice), contentHash(body));
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, `${head}\n${body.trim()}\n`, 'utf8');
  console.log(`WRITE ${rel(path)}`);
  return true;
}

const rel = (p) => p.replace(`${ROOT}/`, '');

/** Topic count of an existing queue file, for error messages only. */
function existsCountSafe(path) {
  try {
    const v = yaml.load(readFileSync(path, 'utf8'));
    return Array.isArray(v) ? v.length : 0;
  } catch {
    return 0;
  }
}
