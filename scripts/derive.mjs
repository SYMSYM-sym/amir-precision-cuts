export function buildForbidden(c) {
  const tpl = yaml.load(readFileSync(join(BRAND_TPL, 'forbidden.template.yaml'), 'utf8'));
  const phrases = new Set((tpl.phrases || []).map(String));
  const words = new Set((tpl.words || []).map(String));

  for (const b of c.brand.banned_extra || []) {
    (String(b).trim().includes(' ') ? phrases : words).add(String(b).trim());
  }

  // Compliance implies bans (R20). The prompt suggests; this enforces.
  const comp = c.compliance || {};
  if (comp.no_medical_claims) ['cures', 'heals', 'treats', 'medical-grade', 'clinically proven'].forEach((w) => words.add(w));
  if (comp.no_guarantees) {
    ['pain-free', 'completely painless', 'guaranteed results', 'risk-free'].forEach((p) => phrases.add(p));
    ['guaranteed', 'painless'].forEach((w) => words.add(w));
  }
  if (comp.no_superlatives_without_evidence) {
    ['the best', 'the ultimate', 'world-class', 'number one'].forEach((p) => phrases.add(p));
  }

  // Vertical-specific cringe. The reference banned "manscaping" because it was a
  // barbershop; a nail lounge needs a different list.
  const VERTICAL = {
    nail: ['mani-pedi', 'nail art goals'],
    lash: ['wispy', 'insta-lashes', 'flutter'],
    brow: ['brows on fleek', 'insta-brows'],
    wax: ['manscaping', 'down there', 'private parts'],
    barber: ['manscaping', 'fresh cut fade life'],
    spa: ['pamper', 'me-time', 'self-care journey'],
    massage: ['rubdown', 'happy ending'],
    tattoo: ['ink slinger', 'tramp stamp'],
  };
  const type = String(c.business.type).toLowerCase();
  for (const [k, list] of Object.entries(VERTICAL)) {
    if (type.includes(k)) list.forEach((t) => (t.includes(' ') ? phrases.add(t) : words.add(t)));
  }

  // A brand must not ban its own vocabulary — that would fail every article.
  const ownWords = new Set(
    [c.business.name, c.business.short_name, c.business.type, ...c.services.map((s) => s.label)]
      .join(' ').toLowerCase().split(/\s+/).filter(Boolean),
  );
  for (const w of [...words]) if (ownWords.has(w.toLowerCase())) words.delete(w);

  return yaml.dump(
    { phrases: [...phrases].sort(), words: [...words].sort() },
    { ...YAML_OPTS, sortKeys: false },
  );
}

