let apiCalls = 0;
function chargeApiCall(what) {
  apiCalls += 1;
  if (apiCalls > MAX_DERIVE_API_CALLS) {
    throw new Error(
      `derive API budget exhausted: ${apiCalls} > content.limits.max_derive_api_calls=` +
        `${MAX_DERIVE_API_CALLS} (tried: ${what}). Full re-derive is a new-business ` +
        'operation; use --only for routine changes.',
    );
  }
}

