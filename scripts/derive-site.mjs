export function fontsHref(cfg) {
  const fams = [cfg.brand.fonts.display, cfg.brand.fonts.body]
    .map((f) => `family=${f.trim().replace(/\s+/g, '+')}:wght@300;400;500;600;700`)
    .join('&');
  return `https://fonts.googleapis.com/css2?${fams}&display=swap`;
}

