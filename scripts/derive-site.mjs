/**
 * derive-site.mjs — renders THE SITE ITSELF from business.config.yaml.
 *
 * 02-DERIVE-BRAIN.md §6: "This is the artifact everyone forgets, and skipping it
 * silently voids the entire factory." The reference `build-blog.mjs` never wrote
 * site/index.html or styles.css at all — they were committed, hand-authored,
 * one-business artifacts. If you derive only the brain, the swap test yields
 * business #2's blog bolted onto business #1's homepage, in business #1's
 * colours, with business #1's address in the footer of every article. It looks
 * like it worked. It is worthless.
 *
 * Outputs (all deterministic — no API call, byte-identical every run):
 *   site/index.html
 *   site/assets/styles.css
 *   robots.txt
 *
 * Never hand-edit any of the three. They are output.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'fs';
import { join } from 'path';
import { render, loadPartials, escapeHtml } from './render-templates.mjs';
import { ROOT, configHash } from './paths.mjs';
import { buildTokens, getVariant, contrastRatio, isDarkTheme } from './layout-variants.mjs';

const TEMPLATES = join(ROOT, 'templates');
const SECTIONS = join(TEMPLATES, 'sections');
const SITE = join(ROOT, 'site');

export const BANNER =
  'GENERATED by npm run derive from business.config.yaml — see 02-DERIVE-BRAIN.md. DO NOT HAND-EDIT.';

// ---------------------------------------------------------------------------
// Google Fonts
