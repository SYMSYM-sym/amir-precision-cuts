export function localBusinessJsonLd(cfg) {
  const { business: b, location: loc, hours, derived } = cfg;
  const ld = {
    '@context': 'https://schema.org',
    '@type': b.category_schema,
    name: b.name,
    url: derived.site_url,
    image: derived.og_image_url,
    logo: derived.logo_url,
    description: b.positioning,
    address: {
      '@type': 'PostalAddress',
      streetAddress: loc.address_street,
      addressLocality: loc.address_city,
      addressRegion: loc.address_region,
      postalCode: loc.address_postal,
      addressCountry: loc.address_country,
    },
    openingHoursSpecification: derived.hours_spec,
    areaServed: (loc.service_area && loc.service_area.length)
      ? [loc.address_city, ...loc.service_area]
      : loc.address_city,
  };
  // priceRange only when we actually have prices — never invent one.
  const priced = (cfg.services || []).filter((s) => s.price_from);
  if (priced.length) ld.priceRange = priceRange(priced);
  // R20 / 04 §A: telephone appears ONLY when the business publishes it.
  if (cfg.booking.publish_phone === true) ld.telephone = cfg.booking.phone;
  if (cfg.booking.publish_email === true) ld.email = cfg.booking.email;
  if (cfg.booking.url) ld.hasMap = derived.address_maps_url;
  if (derived.social_urls.length) ld.sameAs = derived.social_urls;
  if (derived.has_geo) {
    ld.geo = { '@type': 'GeoCoordinates', latitude: Number(loc.latitude), longitude: Number(loc.longitude) };
  }
  if (b.founded_year) ld.foundingDate = String(b.founded_year);
  return ld;
}

function priceRange(priced) {
  const nums = priced
    .map((s) => Number(String(s.price_from).replace(/[^0-9.]/g, '')))
    .filter((n) => Number.isFinite(n) && n > 0);
  if (!nums.length) return undefined;
  const lo = Math.min(...nums);
  const bucket = (n) => (n < 50 ? '$' : n < 120 ? '$$' : n < 250 ? '$$$' : '$$$$');
  const hi = Math.max(...nums);
  return bucket(lo) === bucket(hi) ? bucket(lo) : `${bucket(lo)}-${bucket(hi)}`;
}

export function faqPageJsonLd(cfg) {
  return {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    mainEntity: cfg.homepage.faq.map((f) => ({
      '@type': 'Question',
      name: f.q,
      acceptedAnswer: { '@type': 'Answer', text: f.a },
    })),
  };
}

// ---------------------------------------------------------------------------
// The contact assertion — 04 §A, verbatim: "Never leave this to a human eyeball —
// that's how a client's private number ends up indexed."
// ---------------------------------------------------------------------------

const PHONE_RE = /(?:\+?1[\s.-]?)?\(?\d{3}\)?[\s.-]?\d{3}[\s.-]?\d{4}/;
const EMAIL_RE = /[a-z0-9._%+-]+@[a-z0-9.-]+\.[a-z]{2,}/i;

export function assertNoLeakedContact(html, cfg, label) {
  const problems = [];
  if (cfg.booking.publish_phone !== true) {
    if (/tel:/i.test(html)) problems.push('a tel: link');
    // Strip things that legitimately contain digit runs before scanning.
    const scrub = html
      .replace(/<script[\s\S]*?<\/script>/gi, '')
      .replace(/<style[\s\S]*?<\/style>/gi, '')
      .replace(/https?:\/\/\S+/gi, '')
      .replace(/[a-z-]+="[^"]*"/gi, ' ');
    const m = scrub.match(PHONE_RE);
    if (m) problems.push(`a phone-shaped digit run ("${m[0].trim()}")`);
  }
  if (cfg.booking.publish_email !== true) {
    const scrub = html.replace(/<script[\s\S]*?<\/script>/gi, '');
    if (/mailto:/i.test(scrub)) problems.push('a mailto: link');
    const m = scrub.replace(/<[^>]+>/g, ' ').match(EMAIL_RE);
    if (m) problems.push(`an email address ("${m[0]}")`);
  }
  if (problems.length) {
    throw new Error(
      `CONTACT LEAK in ${label}: found ${problems.join(' and ')}, but the config says ` +
        `publish_phone=${cfg.booking.publish_phone} publish_email=${cfg.booking.publish_email}.\n` +
        'A published private number is not a cosmetic bug — the build fails here on purpose (04 §A).',
    );
  }
}

/** Nothing from another business may survive into the rendered site (§02.6 exit). */
const REFERENCE_FACTS = [
  'Igor For Men', 'igorformen.com', 'West Hollywood', 'Larrabee', "Rene'", '90069', 'IFM',
];

export function assertNoForeignFacts(html, cfg, label) {
  const own = new Set([
    cfg.business.name, cfg.business.short_name, cfg.business.initials,
    cfg.location.address_city, cfg.site.domain,
  ].map((s) => String(s).toLowerCase()));
  const hits = REFERENCE_FACTS.filter(
    (f) => !own.has(f.toLowerCase()) && new RegExp(`\\b${f.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\b`, 'i').test(html),
  );
  if (hits.length) {
    throw new Error(
      `FOREIGN BUSINESS FACT in ${label}: ${hits.join(', ')}. ` +
        'That is an uncut weld — a hardcoded fact from the reference build (14 §C).',
    );
  }
}

