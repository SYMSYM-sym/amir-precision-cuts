/**
 * site-render.mjs — the site renderer. PURE: no fs, no path.
 *
 * 02-DERIVE-BRAIN.md §6 is the reason this exists at all: the reference build
 * never rendered site/index.html or styles.css from anything, so the swap test
 * produced business #2's blog bolted onto business #1's homepage. This module
 * is the fix, and it is kept fs-free so the browser intake portal runs the
 * identical code rather than an approximation of it.
 */
import { render, escapeHtml } from './render-templates.mjs';
import { buildTokens, getVariant, contrastRatio, isDarkTheme } from './layout-variants.mjs';

export const BANNER =
  'GENERATED by npm run derive from business.config.yaml — see 02-DERIVE-BRAIN.md. DO NOT HAND-EDIT.';

// Google Fonts
